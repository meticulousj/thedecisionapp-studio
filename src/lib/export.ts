import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

export type Section =
  | { heading: string; type: "text"; body: string }
  | { heading: string; type: "list"; body: string[]; ordered?: boolean; checklist?: boolean }
  | { heading: string; type: "kv"; body: { k: string; v: string }[] }
  | { heading: string; type: "table"; columns: string[]; rows: (string | number)[][] };

export type ExportPayload = {
  kind: "decision" | "premortem" | "opos" | "assumption" | "ledger";
  toolLabel: string; // eyebrow text e.g. "Decision Suite · Decision Clarity"
  title: string; // first part of title e.g. "Decision"
  titleEm?: string; // italicized second part e.g. "Clarity"
  subtitle?: string;
  sections: Section[];
};

const GOLD: [number, number, number] = [212, 165, 84]; // #D4A554
const TEXT: [number, number, number] = [26, 26, 26];
const MUTED: [number, number, number] = [110, 110, 110];

// ─────────────── Markdown ───────────────
export function toMarkdown(p: ExportPayload): string {
  const lines: string[] = [];
  lines.push(`<!-- ${p.toolLabel} · Generated ${new Date().toISOString().slice(0, 10)} -->`);
  lines.push(`# ${p.title}${p.titleEm ? ` *${p.titleEm}*` : ""}`);
  if (p.subtitle) lines.push(`\n_${p.subtitle}_`);
  lines.push("");

  for (const s of p.sections) {
    lines.push(`## ${s.heading}`);
    lines.push("");
    if (s.type === "text") {
      lines.push(s.body || "_(empty)_");
    } else if (s.type === "list") {
      if (!s.body.length) lines.push("_(none)_");
      else
        s.body.forEach((item, i) => {
          const prefix = s.checklist ? "- [ ]" : s.ordered ? `${i + 1}.` : "-";
          lines.push(`${prefix} ${item}`);
        });
    } else if (s.type === "kv") {
      if (!s.body.length) lines.push("_(none)_");
      else s.body.forEach(({ k, v }) => lines.push(`- **${k}:** ${v}`));
    } else if (s.type === "table") {
      lines.push(`| ${s.columns.join(" | ")} |`);
      lines.push(`| ${s.columns.map(() => "---").join(" | ")} |`);
      if (!s.rows.length) lines.push(`| ${s.columns.map(() => "—").join(" | ")} |`);
      else s.rows.forEach((r) => lines.push(`| ${r.map((c) => String(c).replace(/\|/g, "\\|")).join(" | ")} |`));
    }
    lines.push("");
  }

  lines.push(`---`);
  lines.push(`_Generated by Decision Suite · ${new Date().toLocaleString()}_`);
  return lines.join("\n");
}

// ─────────────── PDF ───────────────
export function toPDF(p: ExportPayload): jsPDF {
  const doc = new jsPDF({ unit: "pt", format: "letter" });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const M = 56; // margin
  let y = M;

  // Eyebrow
  doc.setFont("courier", "normal");
  doc.setFontSize(8);
  doc.setTextColor(...GOLD);
  doc.text(p.toolLabel.toUpperCase(), M, y);
  y += 22;

  // Title
  doc.setFont("times", "bold");
  doc.setFontSize(34);
  doc.setTextColor(...TEXT);
  doc.text(p.title, M, y);
  if (p.titleEm) {
    const w = doc.getTextWidth(p.title + " ");
    doc.setFont("times", "bolditalic");
    doc.setTextColor(...GOLD);
    doc.text(p.titleEm, M + w, y);
    doc.setTextColor(...TEXT);
  }
  y += 14;

  // Gold rule
  doc.setDrawColor(...GOLD);
  doc.setLineWidth(1.2);
  doc.line(M, y, M + 80, y);
  y += 18;

  // Subtitle
  if (p.subtitle) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);
    doc.setTextColor(...MUTED);
    const wrapped = doc.splitTextToSize(p.subtitle, pageW - M * 2);
    doc.text(wrapped, M, y);
    y += wrapped.length * 14 + 8;
  }
  y += 10;

  const ensureSpace = (need: number) => {
    if (y + need > pageH - M - 24) {
      doc.addPage();
      y = M;
    }
  };

  for (const s of p.sections) {
    ensureSpace(60);
    // Section heading
    doc.setFont("helvetica", "bold");
    doc.setFontSize(13);
    doc.setTextColor(...TEXT);
    doc.text(s.heading, M, y);
    y += 6;
    doc.setDrawColor(220, 220, 220);
    doc.setLineWidth(0.5);
    doc.line(M, y, pageW - M, y);
    y += 16;

    if (s.type === "text") {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(11);
      doc.setTextColor(...TEXT);
      const text = s.body?.trim() ? s.body : "(empty)";
      const wrapped = doc.splitTextToSize(text, pageW - M * 2);
      for (const line of wrapped) {
        ensureSpace(16);
        doc.text(line, M, y);
        y += 14;
      }
      y += 8;
    } else if (s.type === "list") {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(11);
      doc.setTextColor(...TEXT);
      if (!s.body.length) {
        doc.setTextColor(...MUTED);
        doc.text("(none)", M, y);
        y += 16;
      } else {
        s.body.forEach((item, i) => {
          const bullet = s.checklist ? "☐" : s.ordered ? `${i + 1}.` : "•";
          const wrapped = doc.splitTextToSize(item, pageW - M * 2 - 20);
          ensureSpace(wrapped.length * 14 + 4);
          doc.setTextColor(...GOLD);
          doc.text(bullet, M, y);
          doc.setTextColor(...TEXT);
          wrapped.forEach((line: string, li: number) => {
            doc.text(line, M + 18, y + li * 14);
          });
          y += wrapped.length * 14 + 4;
        });
      }
      y += 8;
    } else if (s.type === "kv") {
      doc.setFontSize(11);
      if (!s.body.length) {
        doc.setFont("helvetica", "italic");
        doc.setTextColor(...MUTED);
        doc.text("(none)", M, y);
        y += 16;
      } else {
        s.body.forEach(({ k, v }) => {
          ensureSpace(18);
          doc.setFont("helvetica", "bold");
          doc.setTextColor(...TEXT);
          doc.text(`${k}:`, M, y);
          const kw = doc.getTextWidth(`${k}: `);
          doc.setFont("helvetica", "normal");
          const wrapped = doc.splitTextToSize(v || "—", pageW - M * 2 - kw);
          wrapped.forEach((line: string, li: number) => doc.text(line, M + kw, y + li * 14));
          y += wrapped.length * 14 + 4;
        });
      }
      y += 8;
    } else if (s.type === "table") {
      autoTable(doc, {
        startY: y,
        head: [s.columns],
        body: s.rows.length ? s.rows.map((r) => r.map((c) => String(c))) : [s.columns.map(() => "—")],
        margin: { left: M, right: M },
        styles: { font: "helvetica", fontSize: 10, cellPadding: 6, textColor: TEXT },
        headStyles: { fillColor: [245, 240, 230], textColor: TEXT, fontStyle: "bold" },
        alternateRowStyles: { fillColor: [250, 250, 250] },
      });
      y = (doc as any).lastAutoTable.finalY + 16;
    }
  }

  // Footer on every page
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFont("courier", "normal");
    doc.setFontSize(8);
    doc.setTextColor(...MUTED);
    const stamp = `Generated ${new Date().toLocaleDateString()} · Decision Suite · Page ${i} of ${pageCount}`;
    doc.text(stamp, M, pageH - 24);
  }

  return doc;
}

// ─────────────── Helpers ───────────────
export function downloadBlob(filename: string, content: string | Blob, mime = "text/plain") {
  const blob = typeof content === "string" ? new Blob([content], { type: mime }) : content;
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {}
  try {
    const ta = document.createElement("textarea");
    ta.value = text;
    ta.style.position = "fixed";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(ta);
    return ok;
  } catch {
    return false;
  }
}

export function slugify(s: string): string {
  return (s || "export")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40) || "export";
}
